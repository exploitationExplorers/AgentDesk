import { createHmac } from "node:crypto";
import type Database from "better-sqlite3";
import { gatewayDatabase, type GatewayDatabase } from "./database";
import { AppError, ErrorCode } from "@agentdesk/shared";
export class GatewayStore {
  readonly db: GatewayDatabase;
  readonly ready: Promise<void>;
  constructor(
    database: Database.Database | GatewayDatabase,
    private readonly pepper: string,
  ) {
    this.db = gatewayDatabase(database);
    this.ready = this.initialize();
  }
  private async initialize() {
    await this.db.exec(`
      CREATE TABLE IF NOT EXISTS gateway_meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);
      CREATE TABLE IF NOT EXISTS gateway_limits (key TEXT PRIMARY KEY, count INTEGER NOT NULL, resets_at BIGINT NOT NULL);
      CREATE TABLE IF NOT EXISTS gateway_audit (seq ${this.db.dialect === "postgres" ? "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : "INTEGER PRIMARY KEY AUTOINCREMENT"}, user_id TEXT, action TEXT NOT NULL, outcome TEXT NOT NULL, created_at BIGINT NOT NULL);
      CREATE TABLE IF NOT EXISTS gateway_session_auth (session_id TEXT PRIMARY KEY, user_id TEXT NOT NULL, authenticated_at TEXT NOT NULL);
    `);
    const version = (await this.db
      .prepare("SELECT value FROM gateway_meta WHERE key='schema_version'")
      .get()) as
      | {
          value: string;
        }
      | undefined;
    if (version && version.value !== "1") throw new Error("Unsupported gateway schema version");
    await this.db
      .prepare("INSERT INTO gateway_meta VALUES ('schema_version','1') ON CONFLICT(key) DO NOTHING")
      .run();
  }
  async audit(action: string, outcome: string, userId: string | null = null) {
    await this.ready;
    await this.db
      .prepare("INSERT INTO gateway_audit(user_id,action,outcome,created_at) VALUES (?,?,?,?)")
      .run(userId, action, outcome, Date.now());
  }
  /** 同一事务检查全部桶再增加计数；只保留 HMAC，不把邮箱／IP 直接写进限流键。 */
  async limit(
    buckets: Array<{
      key: string;
      max: number;
      windowMs: number;
    }>,
    now = Date.now(),
  ) {
    await this.ready;
    await this.db
      .transaction(async () => {
        await this.db.prepare("DELETE FROM gateway_limits WHERE resets_at<=?").run(now);
        const values = buckets.map((bucket) => ({
          ...bucket,
          key: createHmac("sha256", this.pepper).update(bucket.key).digest("hex"),
        }));
        for (const bucket of values) {
          const row = (await this.db
            .prepare("SELECT count FROM gateway_limits WHERE key=?")
            .get(bucket.key)) as
            | {
                count: number;
              }
            | undefined;
          if (row && row.count >= bucket.max)
            throw new AppError(ErrorCode.RateLimited, "请求过于频繁，请稍后再试");
        }
        for (const bucket of values)
          await this.db
            .prepare(
              `INSERT INTO gateway_limits VALUES (?,1,?)
        ON CONFLICT(key) DO UPDATE SET count=gateway_limits.count+1`,
            )
            .run(bucket.key, now + bucket.windowMs);
      })
      .immediate();
  }
  async revokeAll(userId: string) {
    await this.ready;
    await this.db
      .transaction(async () => {
        await this.db.prepare('DELETE FROM "session" WHERE "userId"=?').run(userId);
        await this.db.prepare("DELETE FROM gateway_session_auth WHERE user_id=?").run(userId);
        await this.audit("sessions.revoke-all", "revoked", userId);
      })
      .immediate();
  }
  async markSessionAuthenticated(userId: string, sessionId: string, at = new Date()) {
    await this.ready;
    await this.db
      .prepare(
        `INSERT INTO gateway_session_auth(session_id,user_id,authenticated_at) VALUES (?,?,?)
      ON CONFLICT(session_id) DO UPDATE SET user_id=excluded.user_id,authenticated_at=excluded.authenticated_at`,
      )
      .run(sessionId, userId, at.toISOString());
  }
  async sessionAuthenticatedAt(userId: string, sessionId: string) {
    await this.ready;
    return (
      (await this.db
        .prepare(
          "SELECT authenticated_at AS at FROM gateway_session_auth WHERE session_id=? AND user_id=?",
        )
        .get(sessionId, userId)) as
        | {
            at: string;
          }
        | undefined
    )?.at;
  }
  async removeSession(sessionId: string) {
    await this.ready;
    await this.db
      .transaction(async () => {
        await this.db.prepare('DELETE FROM "session" WHERE id=?').run(sessionId);
        await this.db.prepare("DELETE FROM gateway_session_auth WHERE session_id=?").run(sessionId);
      })
      .immediate();
  }
}
