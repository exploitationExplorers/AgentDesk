import { describe, expect, it } from "vitest";
import { shellRisk } from "../src/agents/tools";

describe("shellRisk", () => {
  it.each([
    "git status --short",
    "git status --porcelain=v1",
    "git branch",
    "git branch -a -vv",
    "git branch --show-current",
    "git remote -v",
    "git diff --stat",
    "git diff --cached --name-only",
    "git log --oneline -n 5",
    "git log -5",
    "git show HEAD --stat",
    "git show HEAD:src/index.ts",
    "git rev-parse HEAD",
    "git rev-parse --short=12 HEAD",
    "git ls-files --others --exclude-standard",
    "git diff -- README.md apps/cli/README.md",
    'git diff -- "docs/my file.md"',
    "git -c core.safecrlf=false diff --check",
    'git -c "core.safecrlf=false" diff -- README.md',
    "git status --short; git branch --show-current; git rev-parse HEAD; git diff --stat; git diff --cached --stat; git ls-files --others --exclude-standard",
    "git status && git diff --stat",
    "git rev-parse --verify HEAD || git status --short",
    "git status\ngit diff --check",
    "node --version",
    "pwd",
    "whoami",
    "ls -lah",
    "dir /b",
    "echo hello",
  ])("已知只读命令免审批：%s", (command) => {
    expect(shellRisk(command)).toBe("safe");
  });

  it.each([
    "git branch -D work",
    "git branch --delete work",
    "git branch -m old new",
    "git branch new",
    "git branch --set-upstream-to=origin/main",
    "git fetch",
    "git remote -v add origin url",
    "git diff --output=result.txt",
    "git log --output=result.txt",
    "git show --output=result.txt",
    "git diff --ext-diff",
    "git show --textconv",
    "git log --unknown-option",
    "git -c core.pager=command log",
    "git -c core.safecrlf=false -c core.pager=command log",
    "git -c alias.review=command review",
    "git status; git add .",
    "git status && git commit -m update",
    "git status || git push",
    "git ls-files --format=%(path)",
    "git rev-parse --parseopt",
    "git diff --output result.txt",
    "git status &&",
    'git diff -- "unterminated',
    'git diff -- "file$(command).ts"',
    'git diff -- "file%PATH%.ts"',
    "git diff -- src/*.ts; command",
    "git status\ngit branch -D work",
    "git status && echo x",
    "echo %PATH%",
    "echo !command!",
    "echo x^& command",
    "echo $(command)",
    "echo `command`",
    "echo x > file",
    "git status | command",
    "git log -n",
    "git log -n nope",
    'git branch "new name"',
    "dir /b & command",
    "npm run build",
    "",
  ])("变更、展开和未知参数仍需审批：%s", (command) => {
    expect(shellRisk(command)).toBe("dangerous");
  });
});
