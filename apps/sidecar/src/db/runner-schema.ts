/** 远程控制记录采用独立业务表；凭据和浏览器配置不在业务库中。 */
export const RUNNER_CONTROL_SCHEMA_SQL = `
CREATE TABLE IF NOT EXISTS remote_operations (
 operation_id TEXT PRIMARY KEY,user_id TEXT NOT NULL,host_id TEXT NOT NULL,project_id TEXT NOT NULL,
 workspace_id TEXT NOT NULL,action TEXT NOT NULL,request_id TEXT NOT NULL,
 payload_hash TEXT NOT NULL CHECK(length(payload_hash)=64),status TEXT NOT NULL,
 result_json TEXT,created_at TEXT NOT NULL,updated_at TEXT NOT NULL,
 UNIQUE(user_id,host_id,project_id,action,request_id));
CREATE INDEX IF NOT EXISTS remote_operations_scope_idx ON remote_operations(user_id,host_id,project_id,created_at);
CREATE TABLE IF NOT EXISTS remote_project_grants (
 user_id TEXT NOT NULL,host_id TEXT NOT NULL,project_id TEXT NOT NULL,workspace_id TEXT NOT NULL,
 capabilities_json TEXT NOT NULL,connection_epoch INTEGER NOT NULL CHECK(connection_epoch>0),expires_at TEXT NOT NULL,revoked_at TEXT,
 PRIMARY KEY(user_id,host_id,project_id,workspace_id));
CREATE TABLE IF NOT EXISTS remote_task_contexts (
 task_id TEXT PRIMARY KEY,operation_id TEXT NOT NULL UNIQUE REFERENCES remote_operations(operation_id),
 user_id TEXT NOT NULL,host_id TEXT NOT NULL,project_id TEXT NOT NULL,workspace_id TEXT NOT NULL,
 session_id TEXT NOT NULL,recent_auth_at TEXT NOT NULL,executor TEXT NOT NULL CHECK(executor IN ('native-bot','codex')),
 connection_epoch INTEGER NOT NULL CHECK(connection_epoch>0),lease_expires_at TEXT NOT NULL,
 created_seq BIGINT GENERATED BY DEFAULT AS IDENTITY);
CREATE INDEX IF NOT EXISTS remote_task_contexts_scope_idx ON remote_task_contexts(user_id,host_id,project_id);
CREATE TABLE IF NOT EXISTS remote_approval_contexts (
 approval_id TEXT PRIMARY KEY,operation_id TEXT NOT NULL REFERENCES remote_operations(operation_id),
 task_id TEXT REFERENCES remote_task_contexts(task_id),user_id TEXT NOT NULL,host_id TEXT NOT NULL,project_id TEXT NOT NULL,
 workspace_id TEXT NOT NULL,action TEXT NOT NULL,action_digest TEXT NOT NULL CHECK(length(action_digest)=64),
 version INTEGER NOT NULL CHECK(version>0),expires_at TEXT NOT NULL,resolved_by TEXT,decision INTEGER CHECK(decision IN (0,1)),
 created_seq BIGINT GENERATED BY DEFAULT AS IDENTITY,
 CHECK((resolved_by IS NULL AND decision IS NULL) OR (resolved_by IS NOT NULL AND decision IS NOT NULL)));
CREATE TABLE IF NOT EXISTS remote_audit_events (
 seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id TEXT NOT NULL,host_id TEXT NOT NULL,project_id TEXT NOT NULL,
 workspace_id TEXT NOT NULL,action TEXT NOT NULL,request_id TEXT NOT NULL,operation_id TEXT NOT NULL,outcome TEXT NOT NULL,created_at TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS remote_audit_scope_idx ON remote_audit_events(user_id,host_id,project_id,seq);
CREATE TABLE IF NOT EXISTS task_submissions (
 request_id TEXT PRIMARY KEY,payload_hash TEXT NOT NULL,task_id TEXT NOT NULL,run_id TEXT NOT NULL REFERENCES business_runs(id),created_at TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS codex_threads(task_id TEXT PRIMARY KEY,thread_id TEXT NOT NULL UNIQUE);
CREATE TABLE IF NOT EXISTS codex_turns(run_id TEXT PRIMARY KEY,thread_id TEXT NOT NULL,turn_id TEXT,status TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS cloud_repository_imports (
 id TEXT PRIMARY KEY,request_id TEXT UNIQUE NOT NULL,payload_hash TEXT NOT NULL,input_json TEXT NOT NULL,
 status TEXT NOT NULL,project_id TEXT,created_at TEXT NOT NULL,error_code TEXT);
CREATE TABLE IF NOT EXISTS workspace_snapshots (
 id TEXT PRIMARY KEY,user_id TEXT NOT NULL,host_id TEXT NOT NULL,project_id TEXT NOT NULL,request_id TEXT NOT NULL,
 payload_hash TEXT NOT NULL,status TEXT NOT NULL,manifest_json TEXT,created_at BIGINT NOT NULL,
 UNIQUE(user_id,host_id,project_id,request_id));
CREATE TABLE IF NOT EXISTS workspace_transfers (
 id TEXT PRIMARY KEY,user_id TEXT NOT NULL,host_id TEXT NOT NULL,project_id TEXT NOT NULL,request_id TEXT NOT NULL,
 manifest_json TEXT NOT NULL,manifest_hash TEXT NOT NULL,status TEXT NOT NULL,result_json TEXT,created_at BIGINT NOT NULL,
 UNIQUE(user_id,host_id,project_id,request_id));
`;
