import type { PostgresUnitOfWork } from "../../db/postgres";
import type { RetentionStore } from "./ports";

export const RUNNER_TRACE_SCHEMA_SQL = `
CREATE TABLE IF NOT EXISTS business_traces(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,scope TEXT NOT NULL,event JSONB NOT NULL,created_at TIMESTAMPTZ NOT NULL);
CREATE INDEX IF NOT EXISTS business_traces_scope ON business_traces(scope,created_at,id);
`;

/** 分批回收与断点水位在同一事务提交，PG 自行回收空闲页。 */
export class PostgresRetentionStore implements RetentionStore {
  constructor(private readonly db: PostgresUnitOfWork) {}
  async count(
    taskIds: string[],
    conversationIds: string[],
    eventCutoff: string,
    traceCutoff: string,
  ) {
    let events = 0,
      traces = 0;
    for (const id of taskIds)
      events += Number(
        (
          await this.db.query<{ n: string }>(
            "SELECT count(*) AS n FROM (SELECT 1 FROM business_run_events WHERE task_id=$1 AND created_at<$2 LIMIT 1000) AS batch",
            [id, eventCutoff],
          )
        ).rows[0]!.n,
      );
    for (const id of new Set(conversationIds))
      traces += Number(
        (
          await this.db.query<{ n: string }>(
            "SELECT count(*) AS n FROM (SELECT 1 FROM business_traces WHERE scope=$1 AND created_at<$2 LIMIT 1000) AS batch",
            [`chat:${id}`, traceCutoff],
          )
        ).rows[0]!.n,
      );
    return { events, traces };
  }
  async prune(taskId: string, conversationId: string, eventCutoff: string, traceCutoff: string) {
    return this.db.transaction(async () => {
      await this.db.lock(`event:${taskId}`);
      const rows = (
        await this.db.query<{ seq: string; run_id: string }>(
          "SELECT seq,run_id FROM business_run_events WHERE task_id=$1 AND created_at<$2 ORDER BY seq LIMIT 1000 FOR UPDATE",
          [taskId, eventCutoff],
        )
      ).rows;
      for (const row of rows)
        await this.db.query(
          "INSERT INTO business_event_retention VALUES($1,$2,$3) ON CONFLICT(run_id) DO UPDATE SET pruned_through=greatest(business_event_retention.pruned_through,excluded.pruned_through)",
          [row.run_id, taskId, row.seq],
        );
      if (rows.length)
        await this.db.query("DELETE FROM business_run_events WHERE seq=ANY($1::bigint[])", [
          rows.map((row) => row.seq),
        ]);
      const traces = conversationId
        ? ((
            await this.db.query(
              "DELETE FROM business_traces WHERE id IN (SELECT id FROM business_traces WHERE scope=$1 AND created_at<$2 ORDER BY id LIMIT 1000)",
              [`chat:${conversationId}`, traceCutoff],
            )
          ).rowCount ?? 0)
        : 0;
      return { events: rows.length, traces };
    });
  }
  async referencesFile(name: string) {
    return !!(
      await this.db.query(
        `SELECT 1 FROM (
      SELECT data::text AS body FROM business_documents UNION ALL SELECT data::text FROM business_messages
      UNION ALL SELECT event::text FROM business_run_events UNION ALL SELECT event::text FROM business_traces
      UNION ALL SELECT data::text FROM business_artifacts
    ) AS content WHERE strpos(body,$1)>0 LIMIT 1`,
        [name],
      )
    ).rowCount;
  }
  async hasPendingApproval(taskId: string, conversationId: string) {
    return !!(
      await this.db.query(
        `SELECT 1 FROM business_documents WHERE collection='approvals'
      AND data->>'status'='pending' AND (data->'payload'->>'taskId'=$1 OR data->>'conversationId'=$2) LIMIT 1`,
        [taskId, conversationId],
      )
    ).rowCount;
  }
  checkpoint() {}
}
